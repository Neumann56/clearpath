/**
 * 按问题挑要注入的主题。
 *
 * 本轮一个都没命中、但上一轮聊过，且这句很短（"那这个具体怎么弄"），
 * 就把上一轮最后那个主题带上——否则会突然断片。
 * 长问句一般自带主题词，不需要继承；判据用长度而不是"那/这个"这类词，
 * 因为"那我该不该接"和"那你说这单能做吗"都带"那"，后者其实会自己命中。
 */
export function matchTopics(question, activeIds = [], max = 2) {
  const q = String(question || '').toLowerCase();
  const hits = [];
  TOPICS.forEach((t, idx) => {
    let s = 0;
    for (const k of t.keys) if (q.includes(String(k).toLowerCase())) s += score(k);
    if (s > 0) hits.push({ id: t.id, s, idx });
  });
  hits.sort((a, b) => b.s - a.s || a.idx - b.idx);
  const ids = hits.slice(0, max).map((h) => h.id);
  if (ids.length) return { ids, carried: false, matched: true };
  const short = String(question || '').trim().length <= 14;
  if (activeIds.length && short) return { ids: activeIds.slice(-1), carried: true, matched: false };
  return { ids: [], carried: false, matched: false };
}

/** 拼成一段可注入的文本；没命中就返回空串，system prompt 一个字节都不涨。 */
export function knowledgeBlock(question, activeIds = [], max = 2) {
  const { ids, carried } = matchTopics(question, activeIds, max);
  if (!ids.length) return { text: '', ids: [], carried };
  const parts = ids.map((id) => TOPICS.find((t) => t.id === id)).filter(Boolean);
  const text = [
    '【外贸常识】下面是通用的行内经验，不是这票的数。',
    '讲的时候不要往里加任何金额、不要据此推算这票能赚多少——算数只认引擎给的结果。',
    parts.map((p) => `# ${p.title}\n${p.text}`).join('\n\n'),
  ].join('\n');
  return { text, ids, carried };
}
