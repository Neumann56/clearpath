/**
 * 聊天回答里允许出现的站内链接。
 *
 * 为什么要白名单而不是"以 / 开头就行"：`//evil.com` 也以 / 开头（协议相对），
 * `javascript:` 塞在 href 里 HTML 转义根本挡不住。模型还可能被用户话术带偏，
 * 所以这里不依赖 prompt 的自律，路径和参数都按字符集卡死。
 */
export const CHAT_LINK_RE =
  /^\/(?:quote\/(?:new|batch|confirm)|quote\/[0-9a-fA-F-]{8,}\/(?:report|print|calibrate)|reports|calendar|learn|demo\/unresolved|demo\/calibration|market|shop-guide|about|guide)(?:\?[A-Za-z0-9%._~=&;+-]*)?$/;

export function isSafeChatLink(path) {
  return CHAT_LINK_RE.test(String(path || ''));
}

/** 覆盖范围的触发词。只在用户问"能不能算某国/某品类"时才注入，平时一个字都不占。 */
const COVERAGE_KEYS = ['哪些国家', '哪些市场', '哪些品类', '能算', '覆盖', '支持哪些', '这个国家', '这个市场', '算不了'];

/**
 * 「现在到底能算哪些」。
 *
 * 这数据不写死在这里——参数库每加一个国家它就过期了，而过期的清单比没有清单更坏：
 * 用户问"能算越南吗"，老周照过期清单说不能，这单可能就丢了。
 * 所以由调用方从 /api/meta/* 现取，取不到就不注入（宁可让它说"你去下拉看"，也别给旧答案）。
 */
export function coverageBlock(coverage, question) {
  if (!coverage || !coverage.countries?.length) return { text: '', hit: false };
  const q = String(question || '').toLowerCase();
  if (!COVERAGE_KEYS.some((k) => q.includes(k))) return { text: '', hit: false };
  const cn = coverage.countries;
  const cats = coverage.categories || [];
  const text = [
    '# 现在能算哪些',
    `参数版本 ${coverage.asOf || '以页面为准'}。已开放的市场共 ${cn.length} 个：${cn.join('、')}。`,
    cats.length ? `已入库的品类共 ${cats.length} 个：${cats.join('、')}。` : '',
    '用户问某个国家或品类能不能算，照这份清单直接答，别让他自己去下拉里找；不在清单里的，直说"这个还没入库，换个市场或者等参数更新"，不要用一个相近的国家替他估。',
  ].filter(Boolean).join('\n');
  return { text, hit: true };
}

/**
 * 按问题挑要注入的功能条目。最多一条——用户问"怎么算"，给「新预演」就够，
 * 再搭一条「批量」只会让回答变长。
 */
export function matchRoutes(question, max = 1) {
  const q = String(question || '').toLowerCase();
  const hits = [];
  ROUTES.forEach((r, idx) => {
    let s = 0;
    for (const k of r.keys) if (q.includes(String(k).toLowerCase())) s += score(k);
    if (s > 0) hits.push({ id: r.id, s, idx });
  });
  hits.sort((a, b) => b.s - a.s || a.idx - b.idx);
  return hits.slice(0, max).map((h) => h.id);
}

/** 没命中就返回空串，prompt 一个字节都不涨。 */
export function routeBlock(question, max = 1) {
  const ids = matchRoutes(question, max);
  if (!ids.length) return { text: '', ids: [] };
  const parts = ids.map((id) => ROUTES.find((r) => r.id === id)).filter(Boolean);
  return { text: parts.map((p) => `# ${p.title}\n${p.text}`).join('\n\n'), ids };
}
